def mix3(
    n_simple: int,
    n_typical: int,
    n_complex: int,
    simple: tuple[float, float],
    typical: tuple[float, float],
    complex_: tuple[float, float],
) -> tuple[float, float]:
    return (
        round(n_simple * simple[0] + n_typical * typical[0] + n_complex * complex_[0], 2),
        round(n_simple * simple[1] + n_typical * typical[1] + n_complex * complex_[1], 2),
    )


def mix_tc(n_typical: int, n_complex: int, typical: tuple, complex_: tuple) -> tuple[float, float]:
    return (
        round(n_typical * typical[0] + n_complex * complex_[0], 2),
        round(n_typical * typical[1] + n_complex * complex_[1], 2),
    )


