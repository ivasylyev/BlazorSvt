@dataclass
class Row:
    stage: str
    backlog: str
    item: str
    title: str
    status: str  # Done | Partial | Todo
    no_ai: float
    with_ai: float
    done_no_ai: float = 0.0
    done_with_ai: float = 0.0
    note: str = ""

    def __post_init__(self) -> None:
        self.rem_no_ai = round(self.no_ai - self.done_no_ai, 2)
        self.rem_with_ai = round(self.with_ai - self.done_with_ai, 2)
        if abs(self.rem_no_ai) < 0.01:
            self.rem_no_ai = 0.0
        if abs(self.rem_with_ai) < 0.01:
            self.rem_with_ai = 0.0


def R(
    stage: str,
    backlog: str,
    item: str,
    title: str,
    status: str,
    no_ai: float,
    with_ai: float,
    done_frac: float = 0.0,
    note: str = "",
) -> Row:
    d_n = round(no_ai * done_frac, 2)
    d_w = round(with_ai * done_frac, 2)
    return Row(stage, backlog, item, title, status, no_ai, with_ai, d_n, d_w, note)


def R_split(
    stage: str,
    backlog: str,
    item: str,
    title: str,
    status: str,
    no_ai: float,
    with_ai: float,
    done_no_ai: float,
    done_with_ai: float,
    note: str = "",
) -> Row:
    return Row(
        stage, backlog, item, title, status, no_ai, with_ai, done_no_ai, done_with_ai, note
    )


