def sum_fields(rows: Iterable[Row], *attrs: str) -> dict[str, float]:
    out = {a: 0.0 for a in attrs}
    for r in rows:
        for a in attrs:
            out[a] += getattr(r, a)
    return {k: round(v, 1) for k, v in out.items()}


def write_tsv(path: Path, headers: list[str], data_rows: list[list]) -> None:
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter="\t", lineterminator="\n")
        w.writerow(headers)
        for row in data_rows:
            w.writerow(row)


def _wiki_cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def _status_wiki(status: str) -> str:
    return {"Done": "✅ Done", "Partial": "🔶 Partial", "Todo": "⬜ Todo"}.get(status, status)


