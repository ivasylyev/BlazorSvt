def mix_books(n: int, n_complex: int, typical: tuple, complex_: tuple) -> tuple[float, float]:
    n_t = n - n_complex
    return (
        round(n_t * typical[0] + n_complex * complex_[0], 2),
        round(n_t * typical[1] + n_complex * complex_[1], 2),
    )


