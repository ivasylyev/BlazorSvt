    a("У задач тройка в названии; у пакетов и вех — отдельной строкой (сумма листьев по слотам 1–2).")
    a("")
    a("Статусы: `[x]` сделано, `[ ]` не сделано (в т.ч. частично — см. примечание в пункте).")
    a("Нумерация: `{веха}.{пакет}.{задача}`. Номер — очередь исполнения. «Шаг» — шаг кольца, не веха.")
