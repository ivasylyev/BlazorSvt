    a("> Цифры трудоёмкости — `docs/estimation/` (`python docs/estimation/generate_effort_estimate.py`).")
    a("")
    a("**Оценки** в человеко-днях: `(без ИИ / с ИИ / человек)`.")
    a("Первые два слота — оценка ИИ-модели. Третий — оценка человека при работе с ИИ:")
