def fmt(n: float) -> str:
    n = round(float(n), 1)
    if abs(n - round(n)) < 0.05:
        return str(int(round(n)))
    return f"{n:.1f}"


def triple(no_ai: float, with_ai: float, human: str = "—") -> str:
    return f"{fmt(no_ai)} / {fmt(with_ai)} / {human}"


