def emit() -> str:
    rows = apply_new_wbs(build_rows())
    by_stage: dict[str, list] = defaultdict(list)
    by_pkg: dict[str, list] = defaultdict(list)
    for r in rows:
        by_stage[r.stage].append(r)
        by_pkg[r.backlog].append(r)

    lines: list[str] = []
    a = lines.append

    a("# Список работ (бэклог) СВТ 2.0")
    a("")
    a("> Канон чеклиста исполнения. Сводка вех — [roadmap.md](roadmap.md), вручную. Критерии Gate — [cutover.md](cutover.md).")
