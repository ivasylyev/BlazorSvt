$svtBlock2 = [regex]::Replace($svtBlock, '(?m)^- Цель метрик: .+$', '- Цель метрик: Единый вход с проверками вместо Excel/почты/скриптов: {gate}; hit-rate подбора: {hit}; срок ответа vs база «до»: {sla}; ручных заявок в Атласе: {apps_m}; автозаявок по промахам: {apps_a}; доменов в ПЭ: {doms}; поддержка чинит по логам без разработки: {ops}')
