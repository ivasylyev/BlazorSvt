  $title = if ($titleOf.ContainsKey($code)) { $titleOf[$code] } else { $code }
  [void]$block.AppendLine("#### ``$code`` — $title")
  [void]$block.AppendLine('')
  [void]$block.AppendLine('- Критерий/метрика: ' + $metrics[$code])
  [void]$block.AppendLine('')
}
[void]$block.AppendLine('</details>')
[void]$block.AppendLine('')

$insert = $block.ToString()

# Remove old SVT details if any between SVT stream and next stream
$md2 = [regex]::Replace($md, '(?ms)(### Стрим `СВТ`:.*?\r?\n\| `24\.23` \|[^\r\n]+\r?\n)(?:\r?\n<details><summary>Метрики и критерии вех стрима СВТ</summary>.*?</details>\r?\n+)?(?=\r?\n### Стрим `ПРАВ`)', {
  param($m)
  return $m.Groups[1].Value + $insert + "`n### Стрим ``ПРАВ``"
}, 1)

# The replacement above may have broken ПРАВ header - fix carefully
# Simpler approach: find marker and splice
$anchor = '| `24.23` | тираж | 30.06.28 |'
$ai = $md.IndexOf($anchor)
if ($ai -lt 0) { throw 'anchor 24.23 not found' }
$lineEnd = $md.IndexOf("`n", $ai)
if ($lineEnd -lt 0) { throw 'eol after 24.23' }
$after = $lineEnd + 1
# skip following blank lines and optional old details until ### Стрим `ПРАВ`
$rest = $md.Substring($after)
$pm = [regex]::Match($rest, '(?ms)^(?:\s*<details><summary>Метрики и критерии вех стрима СВТ</summary>.*?</details>\s*)?(?=### Стрим `ПРАВ`)')
if (-not $pm.Success) { throw 'ПРАВ marker not found after SVT' }
$newMd = $md.Substring(0, $after) + $insert + $rest.Substring($pm.Length)

