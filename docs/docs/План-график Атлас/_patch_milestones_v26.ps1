  '  <div class="p0-cr"><span class="p0-l">Ресурс</span>' + $res + '</div></div>'
}
function InsertAfterCard([string]$src, [string]$title, [string]$html, [string]$label) {
  $t = '<div class="p0-ct">' + $title + '</div>'
  $c = ([regex]::Matches($src, (Rx $t))).Count
  if ($c -ne 1) { throw "InsertAfterCard '${label}': title count $c" }
  $ti = $src.IndexOf($t)
  $cr = $src.IndexOf('<div class="p0-cr">', $ti)
  $end = $src.IndexOf('</div></div>', $cr) + '</div></div>'.Length
  return $src.Substring(0, $end) + $nl + $html + $src.Substring($end)
}
function InsertAfterLine([string]$src, [string]$line, [string]$html, [string]$label) {
  $c = ([regex]::Matches($src, (Rx $line))).Count
  if ($c -ne 1) { throw "InsertAfterLine '${label}': count $c" }
  $i = $src.IndexOf($line) + $line.Length
  return $src.Substring(0, $i) + $nl + $html + $src.Substring($i)
}

