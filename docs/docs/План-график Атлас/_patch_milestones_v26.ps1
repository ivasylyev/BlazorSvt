function Rx([string]$s) { [regex]::Escape($s) }
function Rep1([string]$text, [string]$old, [string]$new, [string]$label) {
  $c = ([regex]::Matches($text, (Rx $old))).Count
  if ($c -ne 1) { throw "Replace '${label}': expected 1, got $c" }
  return $text.Replace($old, $new)
}
function RepAll([string]$text, [string]$old, [string]$new, [int]$min, [string]$label) {
  $c = ([regex]::Matches($text, (Rx $old))).Count
  if ($c -lt $min) { throw "ReplaceAll '${label}': expected >= $min, got $c" }
  return $text.Replace($old, $new)
}

